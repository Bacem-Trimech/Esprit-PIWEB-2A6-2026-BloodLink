<?php
declare(strict_types=1);

require_once __DIR__ . '/config/config.php';

// 1. Secure session configuration (must come BEFORE session_start)
ini_set('session.use_strict_mode', '1');    // reject session IDs not generated by the server
ini_set('session.cookie_httponly', '1');    // cookie invisible to JavaScript (XSS protection)
ini_set('session.cookie_samesite', 'Lax');  // limits CSRF
// ini_set('session.cookie_secure', '1');   // enable when the site is served over HTTPS
session_start();

// 2. Session expiration due to inactivity
if (isset($_SESSION['last_activity']) && (time() - $_SESSION['last_activity'] > SESSION_LIFETIME)) {
    $_SESSION = [];
    session_destroy();
    session_start();
}
$_SESSION['last_activity'] = time();

// 3. HTTP security headers (fonts.googleapis.com / fonts.gstatic.com are allowed for the Inter font)
header('X-Frame-Options: DENY');
header('X-Content-Type-Options: nosniff');
header('Referrer-Policy: strict-origin-when-cross-origin');
header("Content-Security-Policy: default-src 'self'; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src https://fonts.gstatic.com; img-src 'self' data:; form-action 'self'");

// 4. Classes (Model, Service, Controller)
foreach (['Role', 'User', 'EtablissementSante', 'Medicament', 'GardePharmacie', 'Disponibilite'] as $m) require_once __DIR__ . "/Model/$m.php";
foreach (['UserService', 'AuthService', 'PharmacieService', 'Validator'] as $s) require_once __DIR__ . "/Service/$s.php";
foreach (['BaseController', 'AuthController', 'UserController', 'PharmacieController'] as $c) require_once __DIR__ . "/Controller/$c.php";

$users = new UserService();
if (DEMO_MODE) $users->activateDemoAccounts(DEMO_PASSWORD);
$auth = new AuthService($users);
$authController = new AuthController($auth, $users);
$userController = new UserController($auth, $users);
$pharmacieController = new PharmacieController($auth, $users, new PharmacieService());

// 5. Router: index.php?action=...
$action = $_GET['action'] ?? 'home';
switch ($action) {
    // ---- front office ----
    case 'home':        $authController->home(); break;
    case 'register':    $authController->register(); break;
    case 'login':       $authController->login(); break;
    case 'logout':      $authController->logout(); break;
    case 'dashboard':   $authController->dashboard(); break;
    case 'pharmacies':  $pharmacieController->pharmacies(); break;
    case 'medicaments': $pharmacieController->medicaments(); break;
    // ---- back office: users ----
    case 'admin':       $userController->admin(); break;
    case 'users':       $userController->users(); break;
    case 'user_create': $userController->create(); break;
    case 'user_edit':   $userController->edit(); break;
    case 'user_status': $userController->status(); break;
    case 'user_delete': $userController->delete(); break;
    case 'roles':       $userController->roles(); break;
    // ---- back office: pharmacies module ----
    case 'med_list':     $pharmacieController->medList(); break;
    case 'med_create':   $pharmacieController->medCreate(); break;
    case 'med_edit':     $pharmacieController->medEdit(); break;
    case 'med_delete':   $pharmacieController->medDelete(); break;
    case 'garde_list':   $pharmacieController->gardeList(); break;
    case 'garde_create': $pharmacieController->gardeCreate(); break;
    case 'garde_edit':   $pharmacieController->gardeEdit(); break;
    case 'garde_delete': $pharmacieController->gardeDelete(); break;
    case 'stock_list':   $pharmacieController->stockList(); break;
    case 'stock_save':   $pharmacieController->stockSave(); break;
    case 'stock_delete': $pharmacieController->stockDelete(); break;
    default:            $authController->notFound(); break;
}
